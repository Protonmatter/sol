"""The normal current release build binds compiled outputs to original inputs."""
import hashlib
import json
from pathlib import Path
import sys
import unittest
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'tools'))
import build_web
import validate_release_manifest
import test_release_artifact

class WebBundlingTests(unittest.TestCase):
    def setUp(self):
        self.fixture=test_release_artifact.ReleaseArtifactTests();self.fixture.setUp();self.addCleanup(self.fixture.doCleanups)
        self.root=self.fixture.source
        (self.root/'js').mkdir()
        (self.root/'app.js').write_text("import './js/viewLoader.js';export const load=()=>import('./js/view.js');\n")
        (self.root/'js/viewLoader.js').write_text('export const loader=true;\n')
        (self.root/'js/view.js').write_text("import {value} from './private.js';export const result=value+1;\n")
        (self.root/'js/private.js').write_text('export const value=41;\n')
        descriptor={'schema_version':'startup-modules.v1','roots':['app.js'],'modules':[
            {'url':name,'path':name,'sha256':hashlib.sha256((self.root/name).read_bytes()).hexdigest()}
            for name in ['app.js','js/viewLoader.js']]}
        (self.root/'startup-modules.v1.json').write_text(json.dumps(descriptor))
        (self.root/'index.html').write_text('<meta name="sol-startup-contract" content="startup-modules.v1.json">'
            '<link rel="modulepreload" href="js/viewLoader.js"><script type="module" src="app.js"></script>')
    def test_current_release_compiles_and_binds_private_input(self):
        before={p.relative_to(self.root).as_posix():p.read_bytes() for p in self.root.rglob('*') if p.is_file()}
        out=self.fixture.build('compiled');stage=out/'releases/compiled'
        self.assertTrue((stage/'web-build.v1.json').is_file(),'standard current release must compile')
        descriptor=json.loads((stage/'web-build.v1.json').read_text())
        self.assertFalse((stage/'js/private.js').exists())
        self.assertEqual(descriptor['sources']['apps/web/js/private.js'],hashlib.sha256(before['js/private.js']).hexdigest())
        manifest=json.loads((out/'web-release-manifest.json').read_text())
        for output in descriptor['outputs']:
            asset=next(a for a in manifest['assets'] if a['path']=='releases/compiled/'+output['path'])
            self.assertNotIn('source_path',asset,'generated bytes must not masquerade as a direct source copy')
            self.assertEqual(asset['sha256'],output['sha256'])
        self.assertEqual(before,{p.relative_to(self.root).as_posix():p.read_bytes() for p in self.root.rglob('*') if p.is_file()})
        (self.root/'js/private.js').write_text('export const value=42;\n')
        changed=self.fixture.build('changed')
        after=json.loads((changed/'web-release-manifest.json').read_text())
        self.assertNotEqual(manifest['components']['ui'],after['components']['ui'])
    def test_current_build_failure_does_not_publish_a_partial_artifact(self):
        (self.root/'js/view.js').write_text("import './private.js';import './private.js?v=other';")
        with self.assertRaisesRegex(ValueError,'compil|identit'):
            self.fixture.build('rejected')
        self.assertFalse((self.fixture.root/'rejected').exists())

    def test_rehashed_build_descriptor_cannot_lie_about_compiled_output(self):
        out=self.fixture.build('bound');namespace='releases/bound/'
        descriptor_path=out/namespace/'web-build.v1.json'
        self.assertTrue(descriptor_path.is_file())
        descriptor=json.loads(descriptor_path.read_text());descriptor['outputs'][0]['sha256']='0'*64
        descriptor_path.write_text(json.dumps(descriptor))
        manifest=json.loads((out/'web-release-manifest.json').read_text())
        asset=next(a for a in manifest['assets'] if a['path']==namespace+'web-build.v1.json')
        asset.update(size=descriptor_path.stat().st_size,sha256=hashlib.sha256(descriptor_path.read_bytes()).hexdigest())
        for file in [out/'web-release-manifest.json',out/namespace/'web-release-manifest.json']:
            file.write_text(json.dumps(manifest))
        with self.assertRaisesRegex(ValueError,'compiled|build.*output'):
            validate_release_manifest.validate_manifest(out/'web-release-manifest.json')

    def test_source_delivery_receives_original_private_module_hash(self):
        from unittest.mock import patch
        original=build_web.stage_distribution
        captured={}
        def distribution(*args,**kwargs):
            captured.update(kwargs['web_source_sha256'])
            return original(*args,**kwargs)
        with patch.object(build_web,'stage_distribution',side_effect=distribution):self.fixture.build('archive-inputs')
        self.assertEqual(captured['js/private.js'],hashlib.sha256((self.root/'js/private.js').read_bytes()).hexdigest())

    def test_emitted_code_change_invalidates_both_component_fingerprints(self):
        from unittest.mock import patch
        baseline=self.fixture.build('compiler-baseline')
        before=json.loads((baseline/'web-release-manifest.json').read_text())
        run=build_web.subprocess.run
        def changed_compiler(command,**kwargs):
            result=run(command,**kwargs)
            if result.returncode==0:
                stage=Path(command[-1]);descriptor_file=stage/'web-build.v1.json'
                descriptor=json.loads(descriptor_file.read_text());output=descriptor['outputs'][0]
                file=stage/output['path'];file.write_bytes(file.read_bytes()+b'\n// distinct compiler output\n')
                output['sha256']=hashlib.sha256(file.read_bytes()).hexdigest()
                descriptor_file.write_text(json.dumps(descriptor))
            return result
        with patch.object(build_web.subprocess,'run',side_effect=changed_compiler):changed=self.fixture.build('compiler-change')
        after=json.loads((changed/'web-release-manifest.json').read_text())
        self.assertNotEqual(before['components']['ui'],after['components']['ui'])
        self.assertNotEqual(before['components']['science'],after['components']['science'])

    def test_declared_independent_evidence_must_pass_release_binding(self):
        from unittest.mock import patch
        (self.root/'data/independent-vector-evidence.json').write_text('{}')
        with patch('independent_vector_evidence.validate_release_binding',side_effect=ValueError('independent evidence binding failed')) as gate:
            with self.assertRaisesRegex(ValueError,'independent evidence'):
                self.fixture.build('unbound-evidence')
            gate.assert_called_once_with(build_web.ROOT,self.fixture.wasm)
        self.assertFalse((self.fixture.root/'unbound-evidence').exists())
